"""Derive the readable audit checkpoint from the authoritative ignored ledger."""
import json
import textwrap
from pathlib import Path

root = Path(__file__).resolve().parent
ledger = json.loads((root / 'ledger.json').read_text())
lines = []

def paragraph(text):
    lines.extend(textwrap.wrap(str(text), width=80, break_long_words=False,
                               break_on_hyphens=False))
    lines.append('')

def link(file, start=None):
    suffix = f':{start}' if start else ''
    return f'[{file}{suffix}]({root / "source" / file}{suffix})'

lines.extend(['# Post-merge bespoke audit of #774', ''])
paragraph('Checkpoint only: exhaustive discovery remains incomplete. No lens is '
          'cleared and no complete audit wave has finished. The existing Goal '
          'remains active. Source repairs await complete initial discovery.')
for label, value in [('Merged source', ledger['revision']),
                     ('Comparison base', ledger['base']),
                     ('Final PR head', ledger['pr_head'])]:
    lines.extend([f'- {label}: `{value}`.', ''])
paragraph('The final PR head and merged commit have the same tree. The inventory '
          'contains 746 changed paths, including 699 Rust paths. A separate frozen '
          'source snapshot is audited because the primary checkout is older and '
          'contains unrelated edits. File body reads, contract slices and complete '
          'connected-path discovery are recorded separately.')
paragraph('ledger.json is authoritative; this report is generated by '
          'render_report.py. Source fingerprints and the unrelated working patch '
          'were rechecked without drift. The original stash object remains '
          'present. No new tests, project checks, source edits, CI requests or '
          'external posts were made.')
lines.extend(['## Findings and migration gaps', ''])
paragraph('These entries are source-backed findings, not a claim that discovery '
          'is complete. Their classifications distinguish new checked-error gaps '
          'from retained defects and unfinished migrations. Pending candidates '
          'below are not promoted to defects without the missing evidence.')
ordered = sorted(ledger['findings'], key=lambda x: (x.get('priority') is None,
                                                   x['id']))
for finding in ordered:
    priority = f" ({finding['priority']})" if finding.get('priority') else ''
    lines.extend([f"### {finding['id']}: {finding['title']}{priority}", ''])
    paragraph(finding['classification'])
    for loc in finding.get('locations', []):
        lines.extend(['- ' + link(loc['file'], loc['start']), ''])
    paragraph('Trace: ' + finding.get('contract_trace', ''))
    if finding.get('counterexample'):
        paragraph('Counterexample: ' + finding['counterexample'])
    paragraph('Connected repair: ' + finding['repair'])
    paragraph('Acceptance: ' + finding['acceptance'])
    if finding.get('dependencies'):
        paragraph('Dependencies: ' + '; '.join(finding['dependencies']) + '.')
    for support in finding.get('rule_support', []):
        lines.extend(['Rule: ' + link(support['file'], support['start']) + '.', ''])
    paragraph('Validation: ' + finding.get('validation', 'not run'))
    for trace in finding.get('additional_traces', []):
        paragraph('Additional trace: ' + trace['trace'])
lines.extend(['## Per-lens discovery coverage', '',
              '| Lens | Discovery | Full body reads recorded | Local units closed | Contract slices |',
              '| --- | --- | ---: | ---: | ---: |'])
for lens, state in ledger['lenses'].items():
    full = sum(bool(x.get('body_read_complete'))
               for x in state.get('file_reviews', {}).values())
    lines.append(f"| {lens} | {state['discovery']} | {full} | "
                 f"{len(state.get('reviewed_files', []))} | "
                 f"{len(state.get('examined_contracts', []))} |")
lines.append('')
paragraph('The numerical columns above describe the original coordinator-local records. '
          'Adopted baselines and live continuation evidence use the authoritative '
          'per-lens checkpoints linked in ledger.json and AUDIT-CURRENT.json; these '
          'historical local counts do not replace current coverage. ')
paragraph('Full body reads are not exhaustive producer-to-recipient coverage. '
          'Local units closed is narrower than a family or lens verdict. '
          'The producer pass now includes every changed core file body and '
          'reached strategic, animation and catalogue recipients, but explicit '
          'connected frontiers remain open. Other lenses retain their initial '
          'contract slices and full pending inventories. Finding support from '
          'several lenses does not substitute for their separate complete passes.')
adoption = ledger.get('reconciliation', {}).get('completed_audits_adoption')
if adoption:
    lines.extend(['## Adopted completed audits', ''])
    paragraph('Adler’s admission and type-ownership initial audits cover the '
              'original 2,853 source roles and 246 mandatory overlays WITH_FINDINGS. '
              'Their findings, evidence, aliases, withdrawals and qualifications '
              'are usable now. A fresh exhaustive reread is not a prerequisite. '
              'Only actual changed source, newly reached material and unresolved '
              'qualifications require additional initial reconciliation. Open '
              'findings and final common-revision acceptance remain outstanding.')
    lines.extend([f'[Adoption and bounded delta ledger]({root / adoption})', ''])
historical = ledger.get('reconciliation', {}).get('historical_01_02_adoption')
if historical:
    paragraph('Adler’s completed producer and existing-owner baseline of 2,560 '
              'source roles and 59 overlays is also retained with its findings. '
              'The remaining initial work is the explicit 312-role delta, actual '
              'merged-source changes, qualifications and reached extensions. '
              'Older file-based blanket reread queues are superseded; their '
              'removal does not establish clearance of any outstanding path.')
    progress_path = root / 'reconcile-adler-20261023/audit-continuation/producer-delta/progress.json'
    if progress_path.exists():
        progress = json.loads(progress_path.read_text())
        paragraph(f"Producer delta: {progress['new_material_roles_accounted']} "
                  f"of {progress['new_material_roles_total']} source roles "
                  f"accounted with findings or explicit source questions; first "
                  f"unfinished queue index {progress['first_unfinished_delta_index']}.")
lines.extend(['## Pending candidates and source questions', ''])
for lens, state in ledger['lenses'].items():
    for candidate in state.get('pending_candidates', []):
        lo = candidate.get('lines', [None])[0]
        lines.extend([f"### {candidate['id']}", '', link(candidate['file'], lo), ''])
        paragraph(candidate['observation'])
        for key, label in [('admission_disposition', 'Admission evidence'),
                           ('additional_evidence', 'Additional evidence'),
                           ('producer_disposition', 'Producer disposition')]:
            if candidate.get(key):
                paragraph(label + ': ' + candidate[key])
        paragraph('Next: ' + candidate['next_action'])
lines.extend(['## Recorded boundary dispositions', ''])
for state in ledger['lenses'].values():
    for item in state.get('contract_dispositions', []):
        lines.extend(['### ' + item['contract'], ''])
        paragraph(item['disposition'])
        paragraph('Locations: ' + '; '.join(item['locations']) + '.')
lines.extend(['## Preserved work and coordination', ''])
paragraph('Preserved P16 and P17 recovery commits were inventoried without '
          'restoring files. Their exact commits and changed-file lists are in '
          'preserved-inventory.json. P16 is partial and predates checked timing '
          'interfaces; P17 is not assumed integrated or complete. Neither recovery '
          'can be imported wholesale as a source-complete repair.')
for dependency in ledger.get('unresolved_dependencies', []):
    paragraph(dependency['id'] + ': ' + dependency['scope'] + '. ' +
              dependency['next_action'])
lines.extend(['## Validation limits and continuation', ''])
paragraph('Source reasoning and arithmetic counterexamples were not executed as '
          'new tests. Existing tests were read as evidence; no project checks '
          'were run. Historical CI and previous reviewer verdicts do not clear '
          'this audit. The saved hosted status is only an observation made '
          'earlier at the PR head, not a claim that the run is still running '
          'or that it passed.')
paragraph('Next action: ' + ledger['next_action'])
(root / 'REPORT.md').write_text('\n'.join(lines) + '\n')
print(f"Generated {root / 'REPORT.md'} from ledger.json")
print(f"Findings: {len(ledger['findings'])}; complete waves: 0; cleared lenses: 0")
